import { z } from 'zod';

export const SCHEMA_VERSION = 1;

// ---------------------------------------------------------------------------
// Primitives
// ---------------------------------------------------------------------------

export const IdSchema = z
  .string()
  .min(1)
  .max(64)
  .regex(/^[A-Za-z0-9_-]+$/, 'ids may only contain letters, digits, "_" and "-"');

export const TimeSchema = z.number().finite().min(0).describe('Time in seconds');
export const DurationSchema = z.number().finite().positive().describe('Duration in seconds');
export const ColorSchema = z
  .string()
  .regex(/^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/, 'colors are #RRGGBB or #RRGGBBAA')
  .describe('Color as #RRGGBB or #RRGGBBAA');

// ---------------------------------------------------------------------------
// Project settings and assets
// ---------------------------------------------------------------------------

export const ProjectSettingsSchema = z.object({
  width: z.number().int().min(16).max(7680).default(1920).describe('Output width in pixels'),
  height: z.number().int().min(16).max(4320).default(1080).describe('Output height in pixels'),
  fps: z.number().positive().max(240).default(30).describe('Frames per second'),
  backgroundColor: ColorSchema.default('#000000'),
  sampleRate: z.union([z.literal(44100), z.literal(48000)]).default(48000),
});

export const AssetKindSchema = z.enum(['video', 'audio', 'image']);

export const AssetSchema = z.object({
  id: IdSchema,
  name: z.string().min(1).max(256),
  kind: AssetKindSchema,
  /** Opaque storage key or URL. Core never dereferences it. */
  src: z.string().min(1),
  mimeType: z.string().min(1),
  /** Seconds; null for still images. */
  duration: z.number().nonnegative().nullable(),
  width: z.number().int().positive().nullable().default(null),
  height: z.number().int().positive().nullable().default(null),
  fps: z.number().positive().nullable().default(null),
  hasVideo: z.boolean(),
  hasAudio: z.boolean(),
  sizeBytes: z.number().int().nonnegative().optional(),
  /** Provenance / license note, e.g. "CC0, generated by ffmpeg". */
  source: z.string().max(1000).optional(),
  createdAt: z.string(),
});

// ---------------------------------------------------------------------------
// Visual properties
// ---------------------------------------------------------------------------

export const TransformSchema = z.object({
  x: z.number().finite().default(0).describe('Horizontal offset from canvas center in pixels'),
  y: z.number().finite().default(0).describe('Vertical offset from canvas center in pixels'),
  scale: z
    .number()
    .positive()
    .max(20)
    .default(1)
    .describe('1 = media fit inside the canvas (contain); text: 1 = natural size'),
  rotation: z.number().finite().default(0).describe('Degrees, clockwise'),
  opacity: z.number().min(0).max(1).default(1),
});

export const ANIMATABLE_PROPERTIES = ['x', 'y', 'scale', 'rotation', 'opacity', 'volume'] as const;
export const AnimatablePropertySchema = z.enum(ANIMATABLE_PROPERTIES);

export const EasingSchema = z.enum(['linear', 'easeIn', 'easeOut', 'easeInOut', 'hold']);

export const KeyframeSchema = z.object({
  time: TimeSchema.describe('Seconds relative to the clip start'),
  value: z.number().finite(),
  easing: EasingSchema.default('linear').describe('Easing from this keyframe to the next'),
});

export const KeyframesSchema = z
  .partialRecord(AnimatablePropertySchema, z.array(KeyframeSchema).max(500))
  .describe('Keyframes per animatable property; they override the static value');

export const EffectsSchema = z.object({
  brightness: z.number().min(-1).max(1).optional().describe('-1..1, 0 = unchanged'),
  contrast: z.number().min(-1).max(1).optional().describe('-1..1, 0 = unchanged'),
  saturation: z.number().min(-1).max(1).optional().describe('-1 (grayscale)..1, 0 = unchanged'),
  blur: z.number().min(0).max(50).optional().describe('Gaussian blur radius in pixels'),
});

export const TransitionTypeSchema = z.enum(['crossfade', 'dipToBlack']);
export const TransitionSchema = z.object({
  type: TransitionTypeSchema,
  duration: z.number().positive().max(10),
});

/**
 * Entrance/exit animation presets. Their motion is computed at render time
 * (see `animation.ts`), so trims and splits never leave stale keyframes.
 */
export const ANIMATION_PRESETS = [
  'fade',
  'slide-left',
  'slide-right',
  'slide-up',
  'slide-down',
  'zoom',
  'pop',
] as const;
export const AnimationPresetSchema = z.enum(ANIMATION_PRESETS);
export const AnimationSchema = z.object({
  preset: AnimationPresetSchema,
  duration: z.number().positive().max(10).default(0.5).describe('Seconds (default 0.5)'),
});

export const TextStyleSchema = z.object({
  fontFamily: z.string().min(1).max(200).default('sans-serif'),
  fontSize: z.number().positive().max(1000).default(72).describe('Pixels at output resolution'),
  color: ColorSchema.default('#ffffff'),
  backgroundColor: ColorSchema.nullable().default(null),
  align: z.enum(['left', 'center', 'right']).default('center'),
  bold: z.boolean().default(true),
  italic: z.boolean().default(false),
  strokeColor: ColorSchema.default('#000000'),
  strokeWidth: z.number().min(0).max(50).default(0),
  maxWidth: z.number().min(0.05).max(1).default(0.9).describe('Max line width as canvas fraction'),
});

export const CaptionStyleSchema = z.object({
  fontFamily: z.string().min(1).max(200).default('sans-serif'),
  fontSize: z.number().positive().max(400).default(48),
  color: ColorSchema.default('#ffffff'),
  backgroundColor: ColorSchema.nullable().default('#000000b3'),
  highlightColor: ColorSchema.nullable()
    .default(null)
    .describe('If set, the currently spoken word is drawn in this color'),
  position: z.enum(['bottom', 'middle', 'top']).default('bottom'),
  margin: z.number().min(0).max(0.5).default(0.08).describe('Distance from edge, canvas fraction'),
  maxWidth: z.number().min(0.1).max(1).default(0.85),
});

export const WordSchema = z.object({
  text: z.string().min(1).max(200),
  start: TimeSchema,
  end: TimeSchema,
});

// ---------------------------------------------------------------------------
// Clips
// ---------------------------------------------------------------------------

const clipBase = {
  id: IdSchema,
  start: TimeSchema.describe('Timeline position in seconds'),
  duration: DurationSchema,
  name: z.string().max(256).optional(),
};

const fades = {
  fadeIn: z.number().min(0).max(60).default(0).describe('Fade in seconds (opacity and volume)'),
  fadeOut: z.number().min(0).max(60).default(0).describe('Fade out seconds (opacity and volume)'),
};

const visual = {
  transform: TransformSchema.prefault({}),
  effects: EffectsSchema.prefault({}),
  keyframes: KeyframesSchema.optional(),
  transitionIn: TransitionSchema.optional().describe(
    'Transition from the previous adjacent clip on the same track (or from transparent)',
  ),
  animationIn: AnimationSchema.optional().describe(
    'Entrance animation preset over the first `duration` seconds of the clip',
  ),
  animationOut: AnimationSchema.optional().describe(
    'Exit animation preset over the last `duration` seconds of the clip',
  ),
  ...fades,
};

const audible = {
  volume: z.number().min(0).max(4).default(1).describe('Linear gain, 1 = unchanged'),
  muted: z.boolean().default(false),
};

const media = {
  assetId: IdSchema,
  sourceStart: TimeSchema.default(0).describe('In-point within the asset, seconds'),
};

export const VideoClipSchema = z.object({
  type: z.literal('video'),
  ...clipBase,
  ...media,
  ...visual,
  ...audible,
});

export const AudioClipSchema = z.object({
  type: z.literal('audio'),
  ...clipBase,
  ...media,
  ...audible,
  ...fades,
  keyframes: KeyframesSchema.optional(),
});

export const ImageClipSchema = z.object({
  type: z.literal('image'),
  ...clipBase,
  assetId: IdSchema,
  ...visual,
});

export const TextClipSchema = z.object({
  type: z.literal('text'),
  ...clipBase,
  text: z.string().min(1).max(2000),
  style: TextStyleSchema.prefault({}),
  ...visual,
});

export const ShapeKindSchema = z.enum(['rectangle', 'ellipse']);

/** A vector shape (rectangle / ellipse), sized in project pixels. */
export const ShapeClipSchema = z.object({
  type: z.literal('shape'),
  ...clipBase,
  shape: ShapeKindSchema.default('rectangle'),
  width: z.number().positive().max(16384).default(400).describe('Width in project pixels'),
  height: z.number().positive().max(16384).default(200).describe('Height in project pixels'),
  fill: ColorSchema.nullable().default('#ffffff').describe('Fill color, null for no fill'),
  strokeColor: ColorSchema.default('#000000'),
  strokeWidth: z.number().min(0).max(500).default(0).describe('Outline width in pixels'),
  cornerRadius: z
    .number()
    .min(0)
    .max(8192)
    .default(0)
    .describe('Rectangle corner radius in pixels'),
  ...visual,
});

export const CaptionClipSchema = z.object({
  type: z.literal('caption'),
  ...clipBase,
  text: z.string().min(1).max(2000),
  /** Word timings relative to the clip start (optional, enables word highlighting). */
  words: z.array(WordSchema).max(500).optional(),
});

export const ClipSchema = z.discriminatedUnion('type', [
  VideoClipSchema,
  AudioClipSchema,
  ImageClipSchema,
  TextClipSchema,
  ShapeClipSchema,
  CaptionClipSchema,
]);

export const ClipTypeSchema = z.enum(['video', 'audio', 'image', 'text', 'shape', 'caption']);

// ---------------------------------------------------------------------------
// Tracks and project
// ---------------------------------------------------------------------------

export const TrackKindSchema = z.enum(['video', 'audio', 'caption']);

export const TrackSchema = z.object({
  id: IdSchema,
  kind: TrackKindSchema,
  name: z.string().min(1).max(100),
  muted: z.boolean().default(false),
  hidden: z.boolean().default(false),
  locked: z.boolean().default(false),
  volume: z.number().min(0).max(4).default(1),
  captionStyle: CaptionStyleSchema.optional(),
  clips: z.array(ClipSchema).default([]),
});

export const ProjectSchema = z.object({
  schemaVersion: z.literal(SCHEMA_VERSION),
  id: IdSchema,
  name: z.string().min(1).max(200),
  createdAt: z.string(),
  updatedAt: z.string(),
  settings: ProjectSettingsSchema.prefault({}),
  assets: z.array(AssetSchema).default([]),
  tracks: z.array(TrackSchema).default([]),
});

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type ProjectSettings = z.output<typeof ProjectSettingsSchema>;
export type Asset = z.output<typeof AssetSchema>;
export type AssetKind = z.output<typeof AssetKindSchema>;
export type Transform = z.output<typeof TransformSchema>;
export type AnimatableProperty = z.output<typeof AnimatablePropertySchema>;
export type Easing = z.output<typeof EasingSchema>;
export type Keyframe = z.output<typeof KeyframeSchema>;
export type Keyframes = z.output<typeof KeyframesSchema>;
export type Effects = z.output<typeof EffectsSchema>;
export type Transition = z.output<typeof TransitionSchema>;
export type TransitionType = z.output<typeof TransitionTypeSchema>;
export type AnimationPreset = z.output<typeof AnimationPresetSchema>;
export type Animation = z.output<typeof AnimationSchema>;
export type TextStyle = z.output<typeof TextStyleSchema>;
export type CaptionStyle = z.output<typeof CaptionStyleSchema>;
export type Word = z.output<typeof WordSchema>;
export type VideoClip = z.output<typeof VideoClipSchema>;
export type AudioClip = z.output<typeof AudioClipSchema>;
export type ImageClip = z.output<typeof ImageClipSchema>;
export type TextClip = z.output<typeof TextClipSchema>;
export type CaptionClip = z.output<typeof CaptionClipSchema>;
export type ShapeKind = z.output<typeof ShapeKindSchema>;
export type ShapeClip = z.output<typeof ShapeClipSchema>;
export type Clip = z.output<typeof ClipSchema>;
export type ClipType = z.output<typeof ClipTypeSchema>;
export type MediaClip = VideoClip | AudioClip | ImageClip;
export type VisualClip = VideoClip | ImageClip | TextClip | ShapeClip;
export type TrackKind = z.output<typeof TrackKindSchema>;
export type Track = z.output<typeof TrackSchema>;
export type Project = z.output<typeof ProjectSchema>;

/** Which clip types each track kind accepts. */
export const TRACK_ACCEPTS: Record<TrackKind, readonly ClipType[]> = {
  video: ['video', 'image', 'text', 'shape'],
  audio: ['audio'],
  caption: ['caption'],
};

export function isVisualClip(clip: Clip): clip is VisualClip {
  return (
    clip.type === 'video' || clip.type === 'image' || clip.type === 'text' || clip.type === 'shape'
  );
}

export function isAudibleClip(clip: Clip): clip is VideoClip | AudioClip {
  return clip.type === 'video' || clip.type === 'audio';
}

export function hasSource(clip: Clip): clip is VideoClip | AudioClip {
  return clip.type === 'video' || clip.type === 'audio';
}

export function clipEnd(clip: Pick<Clip, 'start' | 'duration'>): number {
  return clip.start + clip.duration;
}
