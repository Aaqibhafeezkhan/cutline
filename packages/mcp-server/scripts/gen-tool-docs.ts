// Generates docs/mcp-tools.md from the live tool definitions (Zod → JSON Schema via the MCP SDK).
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { z } from 'zod';
import { OperationSchema } from '@cutline/core';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { loadConfig } from '../src/config';
import { createMcpServer, INSTRUCTIONS } from '../src/mcp/server';
import { createServices } from '../src/services';

type Schema = {
  type?: string | string[];
  description?: string;
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  enum?: unknown[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  minimum?: number;
  maximum?: number;
  const?: unknown;
};

const GROUPS: Record<string, string[]> = {
  Editing: [
    'create_project',
    'get_project',
    'add_asset',
    'add_clip',
    'split_clip',
    'trim_clip',
    'move_clip',
    'delete_clip',
    'delete_range',
    'remove_filler_words',
    'delete_words',
    'set_clip_property',
    'set_clip_speed',
    'freeze_frame',
    'animate_clip',
    'add_text_overlay',
    'add_shape',
    'add_template',
    'set_brand_kit',
    'add_captions',
    'add_transition',
    'set_audio_volume',
    'apply_operations',
    'undo',
    'redo',
  ],
  Perception: [
    'get_transcript',
    'get_frames',
    'detect_silence',
    'detect_scenes',
    'get_waveform_summary',
  ],
  Music: ['detect_beats', 'cut_to_beats'],
  Audio: ['duck_music', 'normalize_loudness'],
  'Chapters & highlights': [
    'get_chapters_input',
    'set_chapters',
    'export_chapters',
    'mark_highlights',
    'create_highlight_reel',
  ],
  Output: ['render_preview', 'export_video'],
};

function typeOf(s: Schema): string {
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' | ');
  const variants = s.anyOf ?? s.oneOf;
  if (variants) {
    const parts = [...new Set(variants.map(typeOf))];
    return parts.length > 4 ? 'one of several shapes' : parts.join(' | ');
  }
  if (s.type === 'array') return `${s.items ? typeOf(s.items) : 'any'}[]`;
  if (Array.isArray(s.type)) return s.type.join(' | ');
  return s.type ?? 'any';
}

function range(s: Schema): string {
  const parts = [];
  if (s.minimum !== undefined) parts.push(`≥ ${s.minimum}`);
  if (s.maximum !== undefined) parts.push(`≤ ${s.maximum}`);
  return parts.length ? ` (${parts.join(', ')})` : '';
}

function escape(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function table(schema: Schema, skip: string[] = []): string[] {
  const props = Object.entries(schema.properties ?? {}).filter(([k]) => !skip.includes(k));
  if (props.length === 0) return ['No parameters.', ''];
  const rows = ['| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |'];
  for (const [prop, s] of props) {
    const required = schema.required?.includes(prop) ? 'yes' : '';
    rows.push(
      `| \`${prop}\` | ${escape(typeOf(s))}${range(s)} | ${required} | ${escape(s.description ?? '')} |`,
    );
  }
  return [...rows, ''];
}

async function main() {
  const dataDir = await mkdtemp(join(tmpdir(), 'cutline-docs-'));
  const services = createServices(loadConfig({ dataDir }));
  const server = createMcpServer(services, { id: 'docs' });
  const [a, b] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'docs', version: '1' });
  await Promise.all([server.connect(a), client.connect(b)]);
  const { tools } = await client.listTools();
  const byName = new Map(tools.map((t) => [t.name, t]));

  const lines: string[] = [
    '# MCP tool reference',
    '',
    '<!-- Generated by `pnpm docs:tools` from the Zod schemas. Do not edit by hand. -->',
    '',
    `Cutline exposes ${tools.length} tools. All times are in **seconds**. Every tool returns a one-line`,
    'summary plus compact JSON (also as `structuredContent`); errors carry a code and a hint that',
    'says how to fix the call. `projectId` is optional everywhere: it defaults to the project you',
    'created or used most recently.',
    '',
    '## Server instructions',
    '',
    'Sent to the client on connect:',
    '',
    '```text',
    INSTRUCTIONS,
    '```',
    '',
  ];
  for (const [group, names] of Object.entries(GROUPS)) {
    lines.push(`## ${group}`, '');
    for (const name of names) {
      const tool = byName.get(name);
      if (!tool) throw new Error(`Tool ${name} is not registered`);
      byName.delete(name);
      lines.push(`### \`${name}\``, '');
      lines.push(`**${tool.title ?? name}.** ${tool.description ?? ''}`, '');
      const hints = Object.entries(tool.annotations ?? {})
        .filter(([k, v]) => k.endsWith('Hint') && v)
        .map(([k]) => k.replace('Hint', ''));
      if (hints.length) lines.push(`_Annotations: ${hints.join(', ')}_`, '');
      lines.push(...table(tool.inputSchema as Schema));
    }
  }
  if (byName.size) throw new Error(`Undocumented tools: ${[...byName.keys()].join(', ')}`);

  lines.push(
    '## Operations (`apply_operations`)',
    '',
    'The editor UI and every editing tool are built on these typed operations from `@cutline/core`.',
    'Batch them with `apply_operations` to make several changes as one undo step.',
    '',
  );
  for (const option of OperationSchema.options) {
    const schema = z.toJSONSchema(option, { io: 'input', unrepresentable: 'any' }) as Schema;
    const type = String(schema.properties?.type?.const ?? '?');
    lines.push(`### \`${type}\``, '', ...table(schema, ['type']));
  }

  const out = resolve(import.meta.dirname, '../../../docs/mcp-tools.md');
  await writeFile(out, lines.join('\n'));
  await client.close();
  console.log(`Wrote ${out} (${tools.length} tools, ${OperationSchema.options.length} operations)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
